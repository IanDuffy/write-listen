"""Stage 4: angle + map -> 04_dossier.md

Opus with the API's server-side web search and web fetch. Primary texts first,
then reputable secondary sources. Every claim is numbered [C1], [C2], ... with a
source URL. After the call, every URL the dossier cites is checked against the
URLs the tools actually returned, and the result is appended to the dossier.
"""

from __future__ import annotations

import re

from . import llm
from .common import DOSSIER_ENTRY as ENTRY
from .common import Run, StageError, load_prompt

URL_IN_TEXT = re.compile(r"https?://[^\s)\]>\"'`]+")


def tools(cfg: dict) -> list[dict]:
    rc = cfg["research"]
    return [
        {"type": cfg["tools"]["web_search"], "name": "web_search", "max_uses": rc["max_searches"]},
        {"type": cfg["tools"]["web_fetch"], "name": "web_fetch", "max_uses": rc["max_fetches"],
         "max_content_tokens": rc["max_fetch_tokens"]},
    ]


def retrieved_urls(content: list) -> set[str]:
    """URLs that web search returned or web fetch actually fetched."""
    urls: set[str] = set()
    for block in content:
        btype = getattr(block, "type", None)
        if btype == "web_search_tool_result":
            items = getattr(block, "content", None)
            if isinstance(items, list):  # an error result is a single object, not a list
                for item in items:
                    if getattr(item, "url", None):
                        urls.add(item.url)
        elif btype == "web_fetch_tool_result":
            res = getattr(block, "content", None)
            if getattr(res, "url", None):
                urls.add(res.url)
        elif btype == "text":
            for c in getattr(block, "citations", None) or []:
                if getattr(c, "url", None):
                    urls.add(c.url)
    return urls


def _norm(url: str) -> str:
    url = url.rstrip(".,;:")
    url = re.sub(r"^https?://(www\.)?", "", url)
    url = url.split("#", 1)[0]
    return url.rstrip("/").lower()


def source_check(dossier: str, seen: set[str]) -> str:
    """List cited URLs that never came back from a search or fetch, and entries with no URL."""
    seen_n = {_norm(u) for u in seen}
    cited = {u.rstrip(".,;:") for u in URL_IN_TEXT.findall(dossier)}
    unseen = sorted(u for u in cited if _norm(u) not in seen_n)

    no_url, episode_only = [], []
    entries = list(ENTRY.finditer(dossier))
    for i, m in enumerate(entries):
        end = entries[i + 1].start() if i + 1 < len(entries) else len(dossier)
        entry = dossier[m.start():end]
        if re.search(r"Source:\s*episode\b", entry, re.I):
            episode_only.append(f"C{m.group(1)}")
        elif not URL_IN_TEXT.search(entry):
            no_url.append(f"C{m.group(1)}")

    lines = ["", "## Source check (generated by the research stage)", "",
             f"- Numbered claims: {len(entries)}",
             f"- URLs retrieved by search or fetch: {len(seen)}",
             f"- URLs cited in this dossier: {len(cited)}"]
    if not entries:
        lines.append("- WARNING: no numbered [Cn] claims found. The draft stage needs them.")
    if no_url:
        lines.append(f"- Claims with no source URL: {', '.join(no_url)}")
    if episode_only:
        lines.append("- Claims sourced only to the episode (the researcher worked from the map, not the "
                     f"transcript; check these against the transcript): {', '.join(episode_only)}")
    if unseen:
        lines.append("- Cited URLs that no search or fetch returned. Check these by hand; "
                     "the model may have written them from memory:")
        lines += [f"  - {u}" for u in unseen]
    if entries and not no_url and not unseen:
        lines.append("- Every claim has a URL, and every cited URL was retrieved in this run.")
    return "\n".join(lines) + "\n"


def extract_dossier(text: str) -> str:
    """The model narrates between tool calls; keep only what is inside <dossier> tags."""
    end = text.rfind("</dossier>")
    start = text.rfind("<dossier>", 0, end) if end != -1 else -1
    if start == -1:
        raise StageError("research: no complete <dossier> block in the response.")
    return text[start + len("<dossier>"):end].strip()


def run(r: Run, cfg: dict):
    angle = r.read("angle")
    episode_map = r.read("map")
    r.check_writable("dossier")
    rc = cfg["research"]
    prompt = load_prompt("research", angle=angle, map=episode_map,
                         max_searches=rc["max_searches"], max_fetches=rc["max_fetches"])
    res = llm.call(
        r, cfg, "research",
        messages=[{"role": "user", "content": prompt}],
        tools=tools(cfg),
        expected_searches=rc["max_searches"],
    )
    try:
        dossier = extract_dossier(res.text)
    except StageError:
        (r.root / "_partial_research.md").write_text(res.text, encoding="utf-8")
        raise StageError("research: no <dossier> block in the response; raw output saved to "
                         "_partial_research.md. Nothing was written to 04_dossier.md.") from None
    dossier = dossier.rstrip() + "\n" + source_check(dossier, retrieved_urls(res.content))
    out = r.write("dossier", dossier)
    print(f"  {len(ENTRY.findall(dossier))} numbered claims. See the source check at the end of 04_dossier.md.")
    return out
